import java.util.Base64

plugins {
    java
}

val curseForgeApiKey = providers.environmentVariable("CURSEFORGE_API_KEY").orElse("")
/** 解码内置 Key 的固定盐，必须与 CurseForgeClient.BUNDLED_KEY_SALT 保持一致。 */
val bundledKeySalt = "caml-launcher/curseforge/2026"

/**
 * XOR + Base64 编码。
 *
 * 只用于避免发布包里出现可以被 grep 直接命中的明文 Key，不构成安全边界：
 * 拿到 jar 的人仍然可以还原出 Key。
 */
fun encodeCurseForgeApiKey(raw: String): String {
    val key = raw.trim()
    if (key.isEmpty()) {
        return ""
    }
    val salt = bundledKeySalt.toByteArray(Charsets.UTF_8)
    val bytes = key.toByteArray(Charsets.UTF_8)
    val encoded = ByteArray(bytes.size) { index ->
        (bytes[index].toInt() xor salt[index % salt.size].toInt()).toByte()
    }
    return Base64.getEncoder().encodeToString(encoded)
}

val generateBuildProperties = tasks.register("generateBuildProperties") {
    val outputFile = layout.buildDirectory.file("generated/resources/caml.properties")
    outputs.file(outputFile)
    // Key 只在执行期读取，不参与任务输入，避免被构建扫描记录；任务本身很轻，每次重新生成。
    outputs.upToDateWhen { false }
    doLast {
        val encoded = encodeCurseForgeApiKey(curseForgeApiKey.orNull.orEmpty())
        val file = outputFile.get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            buildString {
                append("# Generated by CAML build. Do not edit.\n")
                if (encoded.isNotEmpty()) {
                    append("caml.curseforge.apikey.enc=").append(encoded).append('\n')
                }
            }
        )
    }
}

sourceSets {
    main {
        resources.srcDir(layout.buildDirectory.dir("generated/resources"))
    }
}

tasks.processResources {
    dependsOn(generateBuildProperties)
}

